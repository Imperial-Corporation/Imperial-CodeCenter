def test_resume_after_interruption_has_no_duplicates(tmp_path):
    files = {f"src/m{i}.py": py_code(f"m{i}") for i in range(6)}
    fake = FakeGitHub(FakeRepo("o/r", files=files), FakeRepo("o/s", files={"b.py": py_code("autre")}))
    run = start(fake, tmp_path)
    fake.hook = lambda r: run.crawler.request_stop() if fake.count("raw") == 3 else None
    first = run.crawler.run()
    done_first = first.files_saved
    assert first.stop_reason == "arret-demande" and 0 < done_first < 7
    assert not run.store.repo_done("o/r", fake.repos["o/r"].commit)   # dépôt interrompu : pas « terminé »
    run.client.close()
    run.store.close()
    before = len(fake.raw_paths())

    fake.hook = None
    second = crawl(fake, tmp_path)
    assert second.stop_reason == "termine"
    assert done_first + second.files_saved == 7
    assert len(files_on_disk(tmp_path)) == 7
    retaken = fake.raw_paths()[before:]
    assert len(retaken) == len(set(retaken)) == 7 - done_first      # rien n'est retéléchargé deux fois
    assert second.files_skipped.get("deja-enregistre") == done_first
    assert "doublon" not in second.files_skipped


