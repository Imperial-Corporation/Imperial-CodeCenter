    stats = run.crawler.run()
    assert not dest.exists()                                       # même pas créé
    assert stats.files_saved == 2 and stats.bytes_written == 0 and stats.files_skipped["doublon"] == 1
    assert fake.count("license") == 0
    assert any("api/" in line and "o/r/src/app.py" in line for line in lines)


