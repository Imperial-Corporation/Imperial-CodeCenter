GENERATED = b"# Code generated by protoc. DO NOT EDIT.\n" + py_code("gen")
MINIFIED = ("var a=1;" * 300).encode()
SECRET = py_code("secret", "\nAWS_KEY = 'AKIAABCDEFGHIJKLMNOP'\n")


def main_repo() -> FakeRepo:
    return FakeRepo("owner/repoa", description="petits outils", files={
        "src/app.py": API_CODE,
        "src/sorter.py": ALGO_CODE,
        "src/plain.py": py_code("plain"),
        "src/dup.py": API_CODE,                       # même contenu que app.py
        "tests/test_app.py": py_code("t"),            # fichier de test
        "src/test_other.py": py_code("t2"),
        "static/app.min.js": MINIFIED,                # minifié (nom)
        "src/bundle.js": MINIFIED,                    # minifié (contenu)
        "src/gen.py": GENERATED,                      # généré
        "src/secret.py": SECRET,                      # secret
        "src/tiny.py": b"x = 1\n",                    # trop petit
        "src/binary.py": b"\x00\x01" * 300,           # binaire
        "README.md": b"# lisez-moi\n" * 50,
    })


def test_full_flow_with_filters(tmp_path):
    other = FakeRepo("owner/repob", license="Apache-2.0", files={"lib/algo_copy.py": ALGO_CODE,
                                                                  "lib/own.py": py_code("own")})
    gpl = FakeRepo("owner/gpl", license="GPL-3.0", files={"a.py": py_code("gpl")})
    nolic = FakeRepo("owner/nolic", license=None, files={"a.py": py_code("nolic")})
    fork = FakeRepo("owner/fork", fork=True, files={"a.py": py_code("fork")})
    old = FakeRepo("owner/old", archived=True, files={"a.py": py_code("old")})
    fake = FakeGitHub(main_repo(), other, gpl, nolic, fork, old)

    stats = crawl(fake, tmp_path)

    assert stats.stop_reason == "termine"
    names = [p.relative_to(tmp_path).as_posix() for p in files_on_disk(tmp_path)]
    assert "api/owner__repoa__src__app.py" in names               # classé « api », nom aplati
    assert "algorithmes/owner__repoa__src__sorter.py" in names
    assert "divers/owner__repoa__src__plain.py" in names
    assert "divers/owner__repob__lib__own.py" in names
    assert len(names) == 4                                         # rien d'autre
    # Licences refusées / fork / archivé : jamais interrogés.
    explored = {r.url.path for r in fake.log if "/branches/" in r.url.path}
    assert explored == {"/repos/owner/repoa/branches/main", "/repos/owner/repob/branches/main"}

    assert stats.files_saved == 4 and stats.repos_done == 2 and stats.repos_seen == 2
    skipped = stats.files_skipped
    assert skipped["test"] == 2 and skipped["trop-petit"] == 1
    assert skipped["genere-ou-minifie"] == 1 and skipped["minifie"] == 1 and skipped["genere"] == 1
    assert skipped["secret"] == 1 and skipped["binaire"] == 1
    assert skipped["doublon"] == 2                                  # dup.py + copie dans repob
    assert "extension" not in skipped                               # README.md n'est pas compté


def test_files_are_written_unmodified_with_license_kept(tmp_path):
    bom_crlf = b"\xef\xbb\xbf" + py_code("bom").replace(b"\n", b"\r\n")
    fake = FakeGitHub(FakeRepo("o/r", files={"src/bom.py": bom_crlf}, license_text="Texte MIT exact\n"))
    crawl(fake, tmp_path)
