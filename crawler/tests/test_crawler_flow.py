def test_repo_level_error_does_not_abort_others_and_is_retried_next_run(tmp_path):
    fake = FakeGitHub(FakeRepo("o/a", files={"a.py": py_code("a")}), FakeRepo("o/b", files={"b.py": py_code("b")}))
    fake.override = lambda r: httpx.Response(409, json={"message": "Git Repository is empty."}) \
        if "/repos/o/a/git/trees" in r.url.path else None
    stats = crawl(fake, tmp_path)
    assert stats.files_saved == 1 and stats.stop_reason == "termine"
    assert any("o/a" in e and "empty" in e for e in stats.errors)
    fake.override = None
    again = crawl(fake, tmp_path)
    assert again.files_saved == 1 and again.repos_skipped == 1


