def test_rerun_after_engine_moved_files_rewrites_nothing(tmp_path):
    fake = FakeGitHub(FakeRepo("o/r", files={"src/a.py": API_CODE, "src/b.py": ALGO_CODE}))
    crawl(fake, tmp_path)
    for p in files_on_disk(tmp_path):                              # le moteur Rust range par langage
        target = p.parent / "python"
        target.mkdir(exist_ok=True)
        p.rename(target / p.name)
    snapshot = sorted(p.relative_to(tmp_path) for p in files_on_disk(tmp_path))
    before = {k: fake.count(k) for k in ("raw", "git/trees", "license", "branches")}

    stats = crawl(fake, tmp_path)
    assert stats.repos_skipped == 1 and stats.files_saved == 0
    assert fake.count("raw") == before["raw"] == 2                  # aucun nouveau téléchargement
    assert fake.count("git/trees") == before["git/trees"]
    assert fake.count("license") == before["license"]
    assert fake.count("branches") == before["branches"] + 1         # seule la tête de branche est relue
    assert sorted(p.relative_to(tmp_path) for p in files_on_disk(tmp_path)) == snapshot


def test_new_commit_after_move_redownloads_but_never_rewrites_known_content(tmp_path):
    repo = FakeRepo("o/r", files={"src/a.py": API_CODE, "src/b.py": ALGO_CODE})
    fake = FakeGitHub(repo)
    crawl(fake, tmp_path)
    for p in files_on_disk(tmp_path):
        (p.parent / "python").mkdir(exist_ok=True)
        p.rename(p.parent / "python" / p.name)
    snapshot = sorted(files_on_disk(tmp_path))

    repo.commit = "f" * 40                                         # nouveau commit, contenu identique + un fichier
    repo.files["src/c.py"] = py_code("nouveau")
    stats = crawl(fake, tmp_path)
    assert stats.files_saved == 1 and stats.files_skipped["doublon"] == 2
    new = sorted(set(files_on_disk(tmp_path)) - set(snapshot))
    assert len(new) == 1 and new[0].name == "o__r__src__c.py"


def test_dry_run_writes_nothing_and_reports(tmp_path):
    dest = tmp_path / "bib"
    lines: list[str] = []
    fake = FakeGitHub(FakeRepo("o/r", files={"src/app.py": API_CODE, "src/b.py": API_CODE, "src/c.py": py_code("c")}))
    run = start(fake, dest, use_store=False, dry_run=True)
