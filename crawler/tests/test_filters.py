import pytest

from icc_crawler.filters import (
    DEFAULT_LICENSES, FilterConfig, content_allowed, language_of, license_allowed, path_allowed, rank_path,
)

CFG = FilterConfig()


@pytest.mark.parametrize("path,size,expected", [
    ("src/app.py", 1000, (True, "")),
    ("main.rs", 500, (True, "")),
    ("README.md", 1000, (False, "extension")),
    ("src/app", 1000, (False, "extension")),
    ("src/app.py", 199, (False, "trop-petit")),
    ("src/app.py", 200, (True, "")),
    ("src/app.py", 60_000, (True, "")),
    ("src/app.py", 60_001, (False, "trop-gros")),
    ("node_modules/lib/index.js", 1000, (False, "dossier-exclu")),
    ("src/Vendor/x.py", 1000, (False, "dossier-exclu")),
    ("src/vendor/x.py", 1000, (False, "dossier-exclu")),
    ("dist/app.js", 1000, (False, "dossier-exclu")),
    ("static/app.min.js", 1000, (False, "genere-ou-minifie")),
    ("static/APP.MIN.JS", 1000, (False, "genere-ou-minifie")),
    ("api/service.pb.go", 1000, (False, "genere-ou-minifie")),
    ("proto/x_pb2.py", 1000, (False, "genere-ou-minifie")),
    ("types/index.d.ts", 1000, (False, "genere-ou-minifie")),
    ("tests/helper.py", 1000, (False, "test")),
    ("src/test_app.py", 1000, (False, "test")),
    ("src/app_test.go", 1000, (False, "test")),
    ("src/app.spec.ts", 1000, (False, "test")),
    ("src/AppTest.java", 1000, (False, "test")),
    ("pkg/__tests__/a.js", 1000, (False, "test")),
])
def test_path_allowed(path, size, expected):
    assert path_allowed(path, size, CFG) == expected


def test_path_allowed_include_tests():
    assert path_allowed("tests/helper.py", 1000, FilterConfig(include_tests=True)) == (True, "")


def test_path_allowed_language_filter():
    config = FilterConfig(languages=frozenset({"rust"}))
    assert path_allowed("a.py", 1000, config) == (False, "langage")
    assert path_allowed("a.rs", 1000, config) == (True, "")


def test_language_of():
    assert language_of("a/b/C.PY") == "python"
    assert language_of("x.hpp") == "cpp"
    assert language_of("x.unknown") is None
    assert language_of("Makefile") is None


@pytest.mark.parametrize("spdx,expected", [
    ("MIT", True), ("mit", True), ("Apache-2.0", True), ("apache-2.0", True),
    ("GPL-3.0", False), ("AGPL-3.0", False), ("NOASSERTION", False), ("", False), (None, False),
])
def test_license_allowed(spdx, expected):
    assert license_allowed(spdx, CFG) is expected


def test_license_allowed_custom_list():
    config = FilterConfig(licenses=frozenset({"GPL-3.0"}))
    assert license_allowed("gpl-3.0", config)
    assert not license_allowed("MIT", config)
    assert "MIT" in DEFAULT_LICENSES and "GPL-3.0" not in DEFAULT_LICENSES


GOOD = ("def f(x):\n    return x + 1\n" * 20).encode()


def test_content_ok_returns_text():
    ok, reason, text = content_allowed(GOOD, CFG)
    assert (ok, reason) == (True, "")
    assert text == GOOD.decode()


def test_content_bom_accepted():
    ok, _, text = content_allowed(b"\xef\xbb\xbf" + GOOD, CFG)
    assert ok and not text.startswith("﻿")


@pytest.mark.parametrize("data,reason", [
    (b"abc\x00def" * 50, "binaire"),
    (b"\xff\xfe\x00\x01" * 100, "binaire"),
    (b"caf\xe9 " * 100, "encodage"),
    (b"", "vide"),
    (b"   \n\n\t\n  ", "vide"),
    (("x = 1; " * 300).encode(), "minifie"),
    (b"# Code generated by protoc. DO NOT EDIT.\n" + GOOD, "genere"),
    (b"// @generated\n" + GOOD, "genere"),
    (b"# This file was generated by tool\n" + GOOD, "genere"),
    (GOOD + b"\nKEY = 'AKIAABCDEFGHIJKLMNOP'\n", "secret"),
    (GOOD + b"\n-----BEGIN RSA PRIVATE KEY-----\nMIIE\n", "secret"),
    (GOOD + b"\n-----BEGIN PRIVATE KEY-----\n", "secret"),
    (GOOD + b"\ntoken = 'ghp_" + b"a" * 36 + b"'\n", "secret"),
    (GOOD + b"\ntoken = 'github_pat_" + b"a" * 60 + b"'\n", "secret"),
    (GOOD + b"\nslack = 'xoxb-1234567890-abcdefg'\n", "secret"),
    (GOOD + b"\nopenai = 'sk-" + b"a" * 40 + b"'\n", "secret"),
    (GOOD + b"\nstripe = 'sk_live_" + b"a" * 30 + b"'\n", "secret"),
    (GOOD + b"\nkey = 'AIza" + b"a" * 35 + b"'\n", "secret"),
])
def test_content_refused(data, reason):
    ok, got, text = content_allowed(data, CFG)
    assert (ok, got, text) == (False, reason, None)


def test_generated_marker_only_in_header():
    late = GOOD + b"# do not edit this please\n"
    assert content_allowed(late, CFG)[0]


def test_max_line_length_configurable():
    data = ("y = '" + "a" * 500 + "'\n").encode()
    assert content_allowed(data, FilterConfig(max_line_length=1000))[0]
    assert content_allowed(data, FilterConfig(max_line_length=100))[1] == "minifie"


def test_rank_path_prefers_examples_and_penalises_depth():
    assert rank_path("examples/a.py", 2000) > rank_path("a/b/c/d/e/f.py", 2000)
    assert rank_path("src/a.py", 2000) > rank_path("zzz/a.py", 2000)
    assert rank_path("a.py", 2000) > rank_path("a/b/c.py", 2000)
