"""Règles de sélection : licences, chemins, taille et qualité du contenu."""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import PurePosixPath

# Licences acceptées par défaut : permissives, à conserver avec attribution.
DEFAULT_LICENSES = frozenset({
    "MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC",
    "Unlicense", "CC0-1.0", "0BSD", "Zlib",
})

# Extension -> (slug de langage, nom GitHub). Alignées sur le moteur Rust.
LANGUAGES: dict[str, tuple[str, str]] = {
    "c": ("c", "C"), "h": ("c", "C"),
    "cc": ("cpp", "C++"), "cpp": ("cpp", "C++"), "cxx": ("cpp", "C++"),
    "hh": ("cpp", "C++"), "hpp": ("cpp", "C++"), "hxx": ("cpp", "C++"),
    "rs": ("rust", "Rust"),
    "py": ("python", "Python"), "pyi": ("python", "Python"),
    "js": ("javascript", "JavaScript"), "jsx": ("javascript", "JavaScript"),
    "mjs": ("javascript", "JavaScript"), "cjs": ("javascript", "JavaScript"),
    "ts": ("typescript", "TypeScript"), "tsx": ("typescript", "TypeScript"),
    "mts": ("typescript", "TypeScript"), "cts": ("typescript", "TypeScript"),
    "java": ("java", "Java"), "cs": ("csharp", "C#"), "go": ("go", "Go"),
    "rb": ("ruby", "Ruby"), "php": ("php", "PHP"), "swift": ("swift", "Swift"),
    "kt": ("kotlin", "Kotlin"), "kts": ("kotlin", "Kotlin"), "scala": ("scala", "Scala"),
    "sh": ("shell", "Shell"), "bash": ("shell", "Shell"),
    "html": ("html", "HTML"), "htm": ("html", "HTML"), "css": ("css", "CSS"),
    "sql": ("sql", "SQL"), "lua": ("lua", "Lua"), "zig": ("zig", "Zig"),
}

# Nom de langage demandé (slug) -> nom attendu par la recherche GitHub.
GITHUB_LANGUAGE_NAMES = {slug: name for slug, name in LANGUAGES.values()}

SKIP_DIRECTORIES = frozenset({
    ".git", ".github", "node_modules", "vendor", "third_party", "third-party", "thirdparty",
    "external", "deps", "dist", "build", "target", "out", "bin", "obj", "__pycache__",
    ".venv", "venv", "env", "site-packages", ".next", ".nuxt", "coverage", "generated", "gen",
    "migrations", "fixtures", "testdata", "snapshots", "__snapshots__",
})

TEST_DIRECTORIES = frozenset({"test", "tests", "__tests__", "spec", "specs", "e2e"})

_SKIP_NAME_RE = re.compile(
    r"(\.min\.(js|css)$|\.bundle\.js$|\.pb\.go$|_pb2(_grpc)?\.py$|\.generated\.|\.g\.(cs|dart)$|"
    r"\.d\.ts$|package-lock\.json$|\.designer\.cs$)", re.IGNORECASE,
)
_TEST_NAME_RE = re.compile(
    r"(^test_.*\.py$|_test\.(py|go|rs|c|cc|cpp)$|\.(test|spec)\.(js|jsx|ts|tsx|mjs)$|Test\.java$|Tests?\.cs$)"
)

_GENERATED_MARKERS = (
    "do not edit", "code generated", "@generated", "auto-generated", "autogenerated",
    "automatically generated", "this file was generated",
)

_SECRET_PATTERNS = [re.compile(p) for p in (
    r"-----BEGIN (?:RSA |EC |OPENSSH |DSA |PGP )?PRIVATE KEY-----",
    r"\bAKIA[0-9A-Z]{16}\b",
    r"\bgh[pousr]_[A-Za-z0-9]{36,}\b",
    r"\bgithub_pat_[A-Za-z0-9_]{50,}\b",
    r"\bxox[baprs]-[A-Za-z0-9-]{10,}\b",
    r"\bsk-[A-Za-z0-9]{32,}\b",
    r"\bAIza[0-9A-Za-z_\-]{35}\b",
    r"\b[sr]k_live_[0-9A-Za-z]{24,}",
    r"hooks\.slack\.com/services/T[A-Z0-9]+/B[A-Z0-9]+/[A-Za-z0-9]+",
)]


@dataclass(frozen=True)
class FilterConfig:
    licenses: frozenset[str] = DEFAULT_LICENSES
    min_bytes: int = 200
    max_bytes: int = 60_000
    max_line_length: int = 1000
    include_tests: bool = False
    languages: frozenset[str] | None = None  # slugs ; None = tous


def extension_of(path: str) -> str:
    return PurePosixPath(path).suffix.lstrip(".").lower()


def language_of(path: str) -> str | None:
    entry = LANGUAGES.get(extension_of(path))
    return entry[0] if entry else None


def license_allowed(spdx_id: str | None, config: FilterConfig) -> bool:
    """Comparaison insensible à la casse (`mit` == `MIT`) ; `NOASSERTION` et vide refusés."""
    if not spdx_id:
        return False
    return spdx_id.lower() in {licence.lower() for licence in config.licenses}


def path_allowed(path: str, size: int, config: FilterConfig) -> tuple[bool, str]:
    """Décide d'après le seul chemin et la taille. Retourne (accepté, motif de refus)."""
    pure = PurePosixPath(path)
    language = language_of(path)

    if language is None:
        return False, "extension"
    if config.languages is not None and language not in config.languages:
        return False, "langage"
    if size < config.min_bytes:
        return False, "trop-petit"
    if size > config.max_bytes:
        return False, "trop-gros"

    directories = {part.lower() for part in pure.parts[:-1]}
    if directories & SKIP_DIRECTORIES:
        return False, "dossier-exclu"
    if _SKIP_NAME_RE.search(pure.name):
        return False, "genere-ou-minifie"
    if not config.include_tests and (directories & TEST_DIRECTORIES or _TEST_NAME_RE.search(pure.name)):
        return False, "test"
    return True, ""


def content_allowed(data: bytes, config: FilterConfig) -> tuple[bool, str, str | None]:
    """Contrôle le contenu téléchargé. Retourne (accepté, motif, texte décodé)."""
    if b"\x00" in data:
        return False, "binaire", None
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        return False, "encodage", None

    lines = text.splitlines()
    if not lines or not text.strip():
        return False, "vide", None
    if max(len(line) for line in lines) > config.max_line_length:
        return False, "minifie", None

    head = "\n".join(lines[:6]).lower()
    if any(marker in head for marker in _GENERATED_MARKERS):
        return False, "genere", None
    if any(pattern.search(text) for pattern in _SECRET_PATTERNS):
        return False, "secret", None
    return True, "", text


def rank_path(path: str, size: int) -> int:
    """Score d'intérêt d'un fichier (plus haut = plus utile comme exemple)."""
    parts = [p.lower() for p in PurePosixPath(path).parts]
    score = 0
    if any(p in ("examples", "example", "samples", "sample", "demo", "demos", "snippets") for p in parts[:-1]):
        score += 30
    if parts and parts[0] in ("src", "lib", "cmd", "pkg", "app", "scripts"):
        score += 10
    if len(parts) == 1:
        score += 5
    if 1_000 <= size <= 15_000:
        score += 10
    score -= 2 * max(0, len(parts) - 3)
    return score
